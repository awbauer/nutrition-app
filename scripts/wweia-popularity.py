"""
Builds src/worker/data/wweia-popularity.ts: how often each FNDDS food was eaten in NHANES
"What We Eat in America" (2021-2023), keyed by the food's normalised description.

Counts are person-days: the number of recall days (day 1 and day 2) on which a respondent
reported the food at least once. FoodData Central's Survey (FNDDS) foods share these descriptions.

Usage (needs pandas):
  python3 scripts/wweia-popularity.py DIR   # DIR holds DR1IFF_L.xpt, DR2IFF_L.xpt, DRXFCD_L.xpt from
                                            # https://wwwn.cdc.gov/Nchs/Data/Nhanes/Public/2021/DataFiles/
"""
import json
import os
import re
import sys
import unicodedata

import pandas as pd


def norm(s: str) -> str:
    # Same as normName in src/worker/lib/foods.ts.
    s = unicodedata.normalize('NFKD', s.lower())
    s = ''.join(c if unicodedata.category(c)[0] in 'LN' or c == ' ' else ' ' for c in s)
    return re.sub(r'\s+', ' ', s).strip()


d = sys.argv[1]
days: dict[int, int] = {}
for f, col in (('DR1IFF_L.xpt', 'DR1IFDCD'), ('DR2IFF_L.xpt', 'DR2IFDCD')):
    t = pd.read_sas(os.path.join(d, f), format='xport')
    t = t[t[col].notna()]
    for code, n in t.groupby(t[col].astype('int64'))['SEQN'].nunique().items():
        days[int(code)] = days.get(int(code), 0) + int(n)

codes = pd.read_sas(os.path.join(d, 'DRXFCD_L.xpt'), format='xport', encoding='latin1')
out: dict[str, int] = {}
for code, desc in zip(codes['DRXFDCD'].astype('int64'), codes['DRXFCLD']):
    k = norm(str(desc))
    out[k] = max(out.get(k, 0), days.get(int(code), 0))

here = os.path.dirname(os.path.abspath(__file__))
path = os.path.join(here, '..', 'src', 'worker', 'data', 'wweia-popularity.ts')
with open(path, 'w') as fh:
    fh.write('// Generated by scripts/wweia-popularity.py from NHANES 2021-2023 dietary recalls (public domain). Do not edit.\n')
    fh.write('// Normalised FNDDS description -> person-days the food was eaten (of 18,000+ recall days).\n')
    fh.write('export const WWEIA_DAYS: Record<string, number> = ')
    fh.write(json.dumps(dict(sorted(out.items())), separators=(',', ':')))
    fh.write(';\n')
print(len(out), 'foods,', sum(1 for v in out.values() if v), 'eaten; wrote', os.path.normpath(path))
