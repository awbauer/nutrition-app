/**
 * Builds and extends test/fixtures/golden-matches.json, the offline evaluation set for the matcher
 * (see test/golden.test.ts and "Matching evaluation" in the README).
 *
 *   npm run golden -- --db <local D1 .sqlite or `wrangler d1 export` .sql> [--refetch] [--vars .dev.vars]
 *   npm run golden -- --queries test/fixtures/golden-queries.json --refetch
 *
 * From a D1 database it takes every AI-logged item that was matched against food databases:
 * - items the user swapped to another food (a food_swapped event): the swapped-to food is the
 *   expected answer (status "reviewed", origin "swap");
 * - the rest: the matcher's own pick, as status "unreviewed". Check each one and set `expect`
 *   and `status: "reviewed"`; unreviewed cases are reported but don't count toward the hit rate.
 * With --queries, it adds the hand-written cases in that file (name, estimate, expected names).
 *
 * Candidates come from the item's stored match (top 8, without FatSecret's result order) or, with
 * --refetch, from a fresh USDA + FatSecret search for the same query, as the matcher would run it
 * (needs USDA_API_KEY and FATSECRET_CONSUMER_KEY/SECRET in --vars; they are only read, never written).
 *
 * Only food names, brands, sources, public database ids and nutrients go into the fixture: no user
 * or item ids, dates, meal text or the user's own custom foods. Existing cases (by id) are kept as
 * they are unless --replace is given, so reviews survive a re-run.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import { FatSecretClient } from '../src/worker/lib/fatsecret';
import { normName } from '../src/worker/lib/foods';
import { MATCH_CONFIG } from '../src/worker/lib/match-config';
import { UsdaClient } from '../src/worker/lib/usda';

export interface GoldenCandidate {
  source: 'usda' | 'fatsecret' | 'cache' | 'history';
  id: string | null;
  name: string;
  brand: string | null;
  data_type: string | null;
  kcal_100g: number | null;
  protein_100g: number | null;
  /** FatSecret's result order (0 = first); null where unknown. */
  source_rank: number | null;
  /** For a food the user had eaten: how often, and the (generic) words used for it. */
  history?: { times: number; names: string[] };
}

export interface GoldenCase {
  id: string;
  origin: 'swap' | 'ai-pick' | 'manual';
  status: 'reviewed' | 'unreviewed';
  note?: string;
  request: { name: string; query: string; brand: string | null; amount: number | null; unit: string | null; estimate_kcal_100g: number | null };
  /** Acceptable chosen food names (case-insensitive); "(estimate)" when no candidate should be used. */
  expect: string[];
  candidates: GoldenCandidate[];
}

const args = process.argv.slice(2);
const flag = (n: string) => args.includes(`--${n}`);
const opt = (n: string) => {
  const i = args.indexOf(`--${n}`);
  return i >= 0 ? args[i + 1] : undefined;
};
const out = opt('out') ?? 'test/fixtures/golden-matches.json';
const fixture: { about: string; cases: GoldenCase[] } = existsSync(out)
  ? JSON.parse(readFileSync(out, 'utf8'))
  : { about: 'Real matching cases for test/golden.test.ts; generated by scripts/golden-matches.ts, then reviewed by hand.', cases: [] };
const byId = new Map(fixture.cases.map((c) => [c.id, c]));
const slug = (s: string) => normName(s).replace(/ /g, '-').slice(0, 60);
/** One id per wording: the item's name, plus the search query when it differs. */
const caseId = (name: string, query: string) => slug(normName(query) === normName(name) ? name : `${name} ${query}`);
const r1 = (n: number | null | undefined) => (n == null ? null : Math.round(n * 10) / 10);

// ---------- live search (optional) ----------
function readVars(path: string): Record<string, string> {
  if (!existsSync(path)) return {};
  return Object.fromEntries(
    readFileSync(path, 'utf8')
      .split('\n')
      .filter((l) => /^\s*[A-Z_]+\s*=/.test(l))
      .map((l) => {
        const i = l.indexOf('=');
        return [
          l.slice(0, i).trim(),
          l
            .slice(i + 1)
            .trim()
            .replace(/^"|"$/g, ''),
        ];
      }),
  );
}
const refetch = flag('refetch');
const vars = refetch ? readVars(opt('vars') ?? '.dev.vars') : {};
if (refetch && !vars.USDA_API_KEY) throw new Error('--refetch needs USDA_API_KEY in --vars (default .dev.vars)');
const usda = refetch ? new UsdaClient(vars.USDA_API_KEY!) : null;
const fatsecret =
  refetch && vars.FATSECRET_CONSUMER_KEY && vars.FATSECRET_CONSUMER_SECRET ? new FatSecretClient(vars.FATSECRET_CONSUMER_KEY, vars.FATSECRET_CONSUMER_SECRET) : null;
const per100 = (n: { code: string; value: number }[], code: string) => r1(n.find((x) => x.code === code)?.value);

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

/** FatSecret, waiting out its rate limit ("too many actions") a few times before giving up on this query. */
async function fatsecretSearch(query: string) {
  if (!fatsecret) return [];
  for (const wait of [10_000, 30_000, 60_000, null]) {
    try {
      return await fatsecret.search(query, MATCH_CONFIG.gather.fatsecretMax);
    } catch (e) {
      if (wait == null) {
        console.warn(`FatSecret failed for "${query}", USDA only: ${(e as Error).message}`);
        return [];
      }
      await sleep(wait);
    }
  }
  return [];
}

/** The same searches the matcher runs (gatherRemote), as fixture candidates. */
async function search(query: string): Promise<GoldenCandidate[]> {
  const u = await usda!.searchAll(query, MATCH_CONFIG.gather.usdaPageSize);
  const f = await fatsecretSearch(query);
  await sleep(1500);
  return [
    ...u.map((h) => ({
      source: 'usda' as const,
      id: h.sourceId,
      name: h.name,
      brand: h.brand,
      data_type: h.dataType,
      kcal_100g: per100(h.nutrients, 'ENERC_KCAL'),
      protein_100g: per100(h.nutrients, 'PROCNT'),
      source_rank: null,
    })),
    ...f.map((h, i) => ({
      source: 'fatsecret' as const,
      id: h.sourceId,
      name: h.name,
      brand: h.brand,
      data_type: h.dataType,
      kcal_100g: per100(h.nutrients, 'ENERC_KCAL'),
      protein_100g: per100(h.nutrients, 'PROCNT'),
      source_rank: i,
    })),
  ];
}

// ---------- cases from a D1 database ----------
interface StoredCandidate {
  source: string;
  fdc_id?: string;
  fatsecret_id?: string;
  food_id?: string;
  name: string;
  brand: string | null;
  data_type: string | null;
  kcal_100g: number | null;
  protein_100g: number | null;
}
interface StoredMatch {
  query: string;
  via: string;
  estimate_kcal_100g: number | null;
  candidates: StoredCandidate[];
  chosen: string | null;
}
const PUBLIC = new Set(['usda', 'fatsecret', 'off']);

function openDb(path: string): DatabaseSync {
  if (path.endsWith('.sql')) {
    const db = new DatabaseSync(':memory:');
    // SQLite keeps sqlite_sequence itself; dumps that write to it can't be replayed.
    const sql = readFileSync(path, 'utf8')
      .split('\n')
      .filter((l) => !l.includes('sqlite_sequence'))
      .join('\n');
    db.exec(sql);
    return db;
  }
  return new DatabaseSync(path, { readOnly: true });
}

function fromDb(path: string): GoldenCase[] {
  const db = openDb(path);
  const aiItems = new Set((db.prepare("SELECT DISTINCT item_id FROM meal_event WHERE kind = 'ai_logged'").all() as { item_id: string }[]).map((r) => r.item_id));
  // The last swap of each item: what the user changed the AI's food to.
  const swaps = new Map<string, { from: string | null; to: string | null; toSource: string | null }>();
  for (const r of db.prepare("SELECT item_id, before_json, after_json FROM meal_event WHERE kind = 'food_swapped' ORDER BY at").all() as {
    item_id: string;
    before_json: string | null;
    after_json: string | null;
  }[]) {
    const b = r.before_json ? JSON.parse(r.before_json) : null;
    const a = r.after_json ? JSON.parse(r.after_json) : null;
    const prev = swaps.get(r.item_id);
    swaps.set(r.item_id, { from: prev?.from ?? b?.food_name ?? null, to: a?.food_name ?? null, toSource: a?.source ?? null });
  }
  const rows = db.prepare('SELECT id, display_name, amount_value, amount_unit, match_json FROM consumed_item WHERE match_json IS NOT NULL').all() as {
    id: string;
    display_name: string;
    amount_value: number;
    amount_unit: string;
    match_json: string;
  }[];
  const cases = new Map<string, GoldenCase>();
  for (const row of rows) {
    if (!aiItems.has(row.id)) continue;
    let m: StoredMatch;
    try {
      m = JSON.parse(row.match_json);
    } catch {
      continue;
    }
    // Only items matched against the food databases (not aliases, custom foods, labels or barcodes).
    if (!['usda', 'fatsecret', 'cache', 'history', 'estimate'].includes(m.via)) continue;
    const swap = swaps.get(row.id);
    const chosen = m.candidates.find((c) => m.chosen != null && [c.fdc_id, c.fatsecret_id, c.food_id].includes(m.chosen));
    // The user's own foods stay out of the fixture.
    if (swap ? !PUBLIC.has(swap.toSource ?? '') : chosen && !PUBLIC.has(chosen.source)) continue;
    const candidates: GoldenCandidate[] = m.candidates
      .filter((c) => PUBLIC.has(c.source))
      .map((c) => ({
        source: c.source === 'fatsecret' ? 'fatsecret' : 'usda',
        id: c.fdc_id ?? c.fatsecret_id ?? null,
        name: c.name,
        brand: c.brand,
        data_type: c.data_type,
        kcal_100g: r1(c.kcal_100g),
        protein_100g: r1(c.protein_100g),
        source_rank: null,
      }));
    const id = caseId(row.display_name, m.query);
    const c: GoldenCase = {
      id,
      origin: swap ? 'swap' : 'ai-pick',
      status: swap?.to ? 'reviewed' : 'unreviewed',
      ...(swap?.to ? { note: `AI chose ${swap.from ?? '?'}; swapped to ${swap.to}` } : {}),
      request: { name: row.display_name, query: m.query, brand: null, amount: row.amount_value, unit: row.amount_unit, estimate_kcal_100g: r1(m.estimate_kcal_100g) },
      expect: swap?.to ? [swap.to] : [chosen?.name ?? '(estimate)'],
      candidates,
    };
    // One case per wording; a swap outranks an unreviewed pick.
    const prev = cases.get(id);
    if (!prev || (prev.origin !== 'swap' && c.origin === 'swap')) cases.set(id, c);
  }
  return [...cases.values()];
}

// ---------- hand-written cases ----------
interface QuerySpec {
  name: string;
  query?: string;
  brand?: string | null;
  amount?: number;
  unit?: string;
  estimate_kcal_100g: number | null;
  expect?: string[];
  note?: string;
}
function fromQueries(path: string): GoldenCase[] {
  const specs: QuerySpec[] = JSON.parse(readFileSync(path, 'utf8'));
  return specs.map((s) => ({
    id: caseId(s.name, s.query ?? s.name),
    origin: 'manual',
    status: s.expect?.length ? 'reviewed' : 'unreviewed',
    ...(s.note ? { note: s.note } : {}),
    request: { name: s.name, query: s.query ?? s.name, brand: s.brand ?? null, amount: s.amount ?? null, unit: s.unit ?? null, estimate_kcal_100g: s.estimate_kcal_100g },
    expect: s.expect ?? [],
    candidates: [],
  }));
}

// ---------- merge ----------
const found: GoldenCase[] = [...(opt('db') ? fromDb(opt('db')!) : []), ...(opt('queries') ? fromQueries(opt('queries')!) : [])];
if (!found.length) {
  console.error('Nothing to add: pass --db <D1 .sqlite/.sql> and/or --queries <file.json>.');
  process.exit(1);
}
const replace = flag('replace');
let added = 0;
let skipped = 0;
for (const c of found) {
  if (byId.has(c.id) && !replace) {
    skipped++;
    continue;
  }
  if (refetch) c.candidates = await search(c.request.query);
  if (!c.candidates.length) {
    console.warn(`skip ${c.id}: no candidates (use --refetch for --queries cases)`);
    continue;
  }
  if (c.status === 'reviewed' && !c.expect.some((e) => e === '(estimate)' || c.candidates.some((x) => x.name.toLowerCase() === e.toLowerCase())))
    c.note = `${c.note ? `${c.note}; ` : ''}expected food not among the candidates`;
  if (byId.has(c.id)) fixture.cases[fixture.cases.findIndex((x) => x.id === c.id)] = c;
  else fixture.cases.push(c);
  byId.set(c.id, c);
  added++;
  // Save as we go: live searches are slow and rate-limited.
  if (refetch) writeFileSync(out, `${JSON.stringify(fixture, null, 2)}\n`);
}
writeFileSync(out, `${JSON.stringify(fixture, null, 2)}\n`);
const unreviewed = fixture.cases.filter((c) => c.status === 'unreviewed').length;
console.log(`${out}: ${added} added or replaced, ${skipped} already there, ${fixture.cases.length} cases (${unreviewed} unreviewed).`);
