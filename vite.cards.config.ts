/**
 * Builds Clem's MCP App card (web/cards) into one self-contained HTML string, written to
 * src/worker/generated/card-html.ts for the Worker to serve as the ui://clem/card.html resource.
 * Hosts render it in a sandboxed iframe, so scripts and styles are inlined: no network needed.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { defineConfig, type Plugin } from 'vite';

const OUT = resolve(import.meta.dirname, 'src/worker/generated/card-html.ts');

function inlineCard(): Plugin {
  return {
    name: 'inline-card',
    apply: 'build',
    generateBundle(_opts, bundle) {
      const js = Object.values(bundle).find((f) => f.type === 'chunk');
      if (!js || js.type !== 'chunk') throw new Error('no card bundle');
      const css = readFileSync(resolve(import.meta.dirname, 'web/cards/card.css'), 'utf8');
      const html = readFileSync(resolve(import.meta.dirname, 'web/cards/card.html'), 'utf8')
        .replace('/*CSS*/', () => css)
        // "</script" inside the bundle would end the inline script early.
        .replace('/*JS*/', () => js.code.replace(/<\/script/gi, '<\\/script'));
      mkdirSync(resolve(OUT, '..'), { recursive: true });
      writeFileSync(OUT, `// Generated by vite.cards.config.ts from web/cards. Do not edit.\nexport const CARD_HTML = ${JSON.stringify(html)};\n`);
      for (const k of Object.keys(bundle)) delete bundle[k]; // nothing else to write
    },
  };
}

export default defineConfig({
  plugins: [inlineCard()],
  build: {
    outDir: resolve(import.meta.dirname, 'node_modules/.cache/clem-card'),
    emptyOutDir: true,
    target: 'es2022',
    minify: true,
    lib: { entry: resolve(import.meta.dirname, 'web/cards/card.ts'), formats: ['es'], fileName: 'card' },
  },
});
